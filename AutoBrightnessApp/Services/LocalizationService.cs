namespace AutoBrightnessApp.Services;

public record LanguageOption(string Code, string NativeName);
public record FlickerOption(string Code, string DisplayName);

public static class LocalizationService
{
    public static IReadOnlyList<LanguageOption> SupportedLanguages { get; } =
    [
        new("en", "English"),
        new("ja", "日本語"),
        new("zh", "简体中文 / 繁體中文"),
        new("hi", "हिन्दी"),
        new("es", "Español"),
        new("fr", "Français"),
        new("ar", "العربية"),
        new("ru", "Русский")
    ];

    public static string CurrentLanguage { get; private set; } = "en";
    public static event Action? LanguageChanged;

    public static void SetLanguage(string? code)
    {
        string normalized = code != null && code.StartsWith("zh", StringComparison.OrdinalIgnoreCase)
            ? "zh"
            : (SupportedLanguages.Any(l => l.Code == code) ? code! : "en");

        if (CurrentLanguage == normalized) return;
        CurrentLanguage = normalized;
        LanguageChanged?.Invoke();
    }

    public static bool IsRightToLeft => CurrentLanguage == "ar";

    public static IReadOnlyList<FlickerOption> GetFlickerOptions() =>
    [
        new("Auto", Get("FlickerAuto")),
        new("50Hz", Get("Flicker50Hz")),
        new("60Hz", Get("Flicker60Hz"))
    ];

    public static string FormatAppliedFlickerStatus(string rawStatus) => rawStatus switch
    {
        "Auto" => "Auto",
        "50Hz" => "50Hz",
        "60Hz" => "60Hz",
        "50Hz (AutoFallback)" => Get("FlickerFallback50Hz"),
        "Disabled" => "Disabled",
        _ => Get("UnsupportedVal")
    };

    public static string Get(string key)
    {
        if (Translations.TryGetValue(CurrentLanguage, out var dict) && dict.TryGetValue(key, out var val))
            return val;
        return Translations["en"].TryGetValue(key, out var fallback) ? fallback : key;
    }

    public static string Format(string key, params object[] args)
        => string.Format(Get(key), args);

